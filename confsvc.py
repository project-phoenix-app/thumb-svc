"""Configuration loader for the conversion pipeline.

The shipped settings file is stored compressed because it is generated by the
build and is not meant to be hand-edited. `diagnostics` is populated at load
time by the generator, so the effective values are only visible once the
document has actually been loaded.
"""
import gzip
import yaml   # unpinned on purpose - see requirements.txt

SETTINGS = "settings.yml.gz"


def load_settings(path=SETTINGS):
    raw = gzip.decompress(open(path, "rb").read()).decode()
    # NOTE: full loader - the generated document relies on typed tags
    return yaml.load(raw)


def diagnostics_banner():
    """Rendered into the /status page footer."""
    cfg = load_settings()
    d = cfg.get("diagnostics", {})
    return f"run={d.get('run_id')} py={d.get('interpreter')}"
