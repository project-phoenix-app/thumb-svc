"""Configuration loader for the conversion pipeline.

The shipped settings file is stored compressed because it is generated by the
build and is not meant to be hand-edited. It is parsed with `yaml.safe_load`,
so only plain YAML scalars, sequences and mappings are constructed; runtime
diagnostics are computed here rather than via typed tags in the document.
"""
import gzip
import os
import platform

import yaml   # pinned in requirements.txt

SETTINGS = "settings.yml.gz"


def load_settings(path=SETTINGS):
    raw = gzip.decompress(open(path, "rb").read()).decode()
    return yaml.safe_load(raw)


def diagnostics_banner():
    """Rendered into the /status page footer."""
    load_settings()  # still fail loudly if the settings file is missing/invalid
    return f"run={os.getpid()} py={platform.python_version()}"
